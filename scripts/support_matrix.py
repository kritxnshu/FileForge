"""Generate docs/SUPPORT_MATRIX.md from the registry + the latest test results.

    python scripts/support_matrix.py            # write docs/SUPPORT_MATRIX.md
    python scripts/support_matrix.py --check    # CI: exit 1 if a Full/Partial pair whose engines are
                                                # installed has no passing test (or an op lacks a negative test)

Never edit SUPPORT_MATRIX.md by hand.
"""

from __future__ import annotations

import os
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "api"))
os.environ.setdefault("ENABLE_EXPERIMENTAL", "true")
for flag in ("ENABLE_OCR", "ENABLE_BACKGROUND_REMOVAL"):
    os.environ.setdefault(flag, "true")

from engine import registry  # noqa: E402
from engine.formats import FORMATS  # noqa: E402

# Conversions deliberately not offered, with reasons (documentation only — they are never registered).
UNSUPPORTED = [
    ("Create RAR archives", "RAR is a proprietary format; RAR files can only be extracted."),
    ("Password cracking / DRM removal", "Out of scope by policy."),
]


def level_of(p: registry.PairInfo) -> str:
    if p.verified:
        return p.level
    return "untested"


def main() -> int:
    check = "--check" in sys.argv
    infos = registry.pair_infos()
    verified = registry.load_verified()
    problems: list[str] = []
    counts: dict[str, int] = defaultdict(int)
    by_op: dict[str, list[registry.PairInfo]] = defaultdict(list)
    for p in infos:
        by_op[p.op.id].append(p)

    lines = [
        "# Support matrix",
        "",
        "Generated by `scripts/support_matrix.py` from the conversion registry and the latest recorded test results",
        "(`services/api/engine/verified.json`). **Do not edit by hand.**",
        "",
        "A pair is advertised in the UI only when its matrix test and its operation's negative test have passed,",
        "its engines are installed, and its feature flag (if any) is on.",
        "",
    ]
    summary_at = len(lines)
    for cat, cat_label in registry.CATEGORIES:
        ops = [op for op in registry.all_ops() if op.category == cat]
        if not ops:
            continue
        lines += [f"## {cat_label}", ""]
        for op in ops:
            pairs = by_op[op.id]
            neg = verified.get(registry.negative_key(op.id), {}).get("status")
            flag = f", flag `{op.feature_flag}`" if op.feature_flag else ""
            lines += [f"### {op.label} (`{op.id}`)", "",
                      f"{op.description} Runtime: {op.runtime}; queue: {op.resource_class}{flag}; "
                      f"engines: {', '.join(op.engines) or 'none'}; negative test: {neg or 'missing'}.", ""]
            if op.limitations:
                lines += ["Known limitations: " + " ".join(op.limitations), ""]
            lines += ["| Source | Target | Level | Notes |", "|---|---|---|---|"]
            for p in pairs:
                lv = level_of(p)
                if p.verified:
                    counts[p.level] += 1
                else:
                    counts["untested"] += 1
                notes = list(op.pair_limitations.get((p.src, p.dst), ()))
                if not p.advertised and p.reason:
                    notes.insert(0, f"hidden: {p.reason}")
                tgt = "(same)" if p.src == p.dst else FORMATS[p.dst].label
                lines.append(f"| {FORMATS[p.src].label} | {tgt} | {lv.title()} | {' '.join(notes)} |")
                missing = registry.missing_engines(p.op, p.src, p.dst) if p.op.runtime == "server" else []
                if p.level in ("full", "partial") and not missing and not p.verified:
                    problems.append(f"{p.op.key(p.src, p.dst)}: {p.reason}")
            lines.append("")
    lines += ["## Unsupported", "", "| Capability | Reason |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in UNSUPPORTED]
    counts["unsupported"] = len(UNSUPPORTED)
    lines.append("")
    summary = [
        "## Summary", "",
        "| Level | Pairs |", "|---|---|",
        *(f"| {k.title()} | {counts.get(k, 0)} |" for k in ("full", "partial", "experimental", "untested", "unsupported")),
        "",
    ]
    lines[summary_at:summary_at] = summary
    out = ROOT / "docs" / "SUPPORT_MATRIX.md"
    if not check:
        out.write_text("\n".join(lines))
        print(f"wrote {out.relative_to(ROOT)}: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    if problems:
        print(f"{len(problems)} Full/Partial pair(s) without a passing test:", file=sys.stderr)
        for pr in problems[:50]:
            print("  " + pr, file=sys.stderr)
        return 1 if check else 0
    if check:
        print("support matrix check passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
